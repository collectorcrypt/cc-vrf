import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { Keypair } from "@solana/web3.js";
import { sha256 } from "@noble/hashes/sha2.js";
import {
  batchLeafFromPack,
  batchLeafV1,
  batchNode,
  buildBatch,
  bytesToHex,
  CC_VRF_PROGRAM_ID,
  deriveAuthorityAddress,
  encodeLabel,
  generateKeyPair,
  hexToBytes,
  proveVRF,
  verifyBatchCommitEndToEnd,
  verifyBatchPath,
  verifyInclusion,
  vrfProofToHash,
  vrfStream,
} from "../src";
import type { BatchCommit, OnChainAuthority } from "../src";

// The one corpus both implementations check (generated by crates/cc-vrf-verify).
const corpus = JSON.parse(
  readFileSync(
    join(__dirname, "../../../crates/cc-vrf-verify/vectors/batch-v1.json"),
    "utf8",
  ),
);
const fixtures = corpus.fixtures.map(
  (f: { alpha: string; proof: string; beta: string }) => ({
    alpha: hexToBytes(f.alpha),
    proof: hexToBytes(f.proof),
    beta: hexToBytes(f.beta),
  }),
);
const leaf = (i: number) => {
  const f = fixtures[i % fixtures.length];
  return batchLeafV1({
    memo: `vector-${i}`,
    alpha: f.alpha,
    proof: f.proof,
    beta: f.beta,
  });
};
const leaves = Array.from({ length: 4096 }, (_, i) => leaf(i));

describe("batch spec v1 corpus", () => {
  it("rebuilds the first leaves", () => {
    corpus.leaves_first_8.forEach((hex: string, i: number) =>
      expect(bytesToHex(leaves[i])).toBe(hex),
    );
  });

  it("matches every root and path, and the paths verify", () => {
    for (const c of corpus.cases) {
      const b = buildBatch(leaves.slice(0, c.count));
      expect(bytesToHex(b.root), `root of ${c.count}`).toBe(c.root);
      for (const p of c.paths) {
        const path = b.path(p.index);
        expect(path.map(bytesToHex), `path ${p.index}/${c.count}`).toEqual(
          p.path,
        );
        expect(
          verifyInclusion(b.root, c.count, p.index, leaves[p.index], path),
        ).toBe(true);
      }
    }
  });

  it("vrfStream re-export matches the corpus stream blocks", () => {
    for (const v of corpus.stream) {
      const bytes = vrfStream(fixtures[v.fixture].beta, ...v.path).nextBytes(
        v.bytes.length / 2,
      );
      expect(bytesToHex(bytes)).toBe(v.bytes);
    }
  });
});

describe("verifyInclusion", () => {
  const n = 13;
  const i = 5;
  const b = buildBatch(leaves.slice(0, n));
  const p = b.path(i);

  it("verifies every index of every size up to 40", () => {
    for (let size = 1; size <= 40; size++) {
      const bb = buildBatch(leaves.slice(0, size));
      for (let j = 0; j < size; j++)
        expect(verifyInclusion(bb.root, size, j, leaves[j], bb.path(j))).toBe(
          true,
        );
    }
  });

  it("refuses tampering", () => {
    expect(verifyInclusion(b.root, n, n, leaves[i], p)).toBe(false);
    expect(verifyInclusion(b.root, n, i + 1, leaves[i], p)).toBe(false);
    for (const wrong of [0, 5, 6, 8, 17, 32])
      expect(verifyInclusion(b.root, wrong, i, leaves[i], p)).toBe(false);
    expect(verifyInclusion(b.root, n, i, leaves[i], p.slice(0, -1))).toBe(
      false,
    );
    expect(verifyInclusion(b.root, n, i, leaves[i], [...p, leaves[0]])).toBe(
      false,
    );
    expect(
      verifyInclusion(b.root, n, i, leaves[i], [p[1], p[0], ...p.slice(2)]),
    ).toBe(false);
    const inner = batchNode(leaves[4], leaves[5]);
    expect(verifyInclusion(b.root, n, 2, inner, p.slice(1))).toBe(false);
    expect(verifyInclusion(b.root, 1 << 21, i, leaves[i], p)).toBe(false);
  });

  it("documents same-shape counts: the verifier must use the committed count", () => {
    for (let c = 9; c <= 16; c++)
      expect(verifyInclusion(b.root, c, i, leaves[i], p)).toBe(true);
  });

  it("verifyBatchPath rebuilds the leaf from fields", () => {
    const f = fixtures[i % fixtures.length];
    const fields = {
      memo: `vector-${i}`,
      alpha: f.alpha,
      proof: f.proof,
      beta: f.beta,
    };
    expect(
      verifyBatchPath({ root: b.root, count: n, index: i, fields, path: p }),
    ).toBe(true);
    const beta = Uint8Array.from(f.beta);
    beta[0] ^= 1;
    expect(
      verifyBatchPath({
        root: b.root,
        count: n,
        index: i,
        fields: { ...fields, beta },
        path: p,
      }),
    ).toBe(false);
    expect(() =>
      batchLeafV1({ ...fields, proof: f.proof.slice(0, 32) }),
    ).toThrow(/80 bytes/);
  });
});

describe("batchLeafFromPack", () => {
  it("equals batchLeafV1 and refuses a stored beta that disagrees with the proof", () => {
    const { sk } = generateKeyPair();
    const alpha = sha256(new TextEncoder().encode("pack-alpha"));
    const { proof } = proveVRF(sk, alpha);
    const beta = vrfProofToHash(proof);
    const pack = {
      memo: "cc-123",
      alphaHex: bytesToHex(alpha),
      proofHex: bytesToHex(proof),
      betaHex: "0x" + bytesToHex(beta),
    };
    expect(bytesToHex(batchLeafFromPack(pack))).toBe(
      bytesToHex(batchLeafV1({ memo: "cc-123", alpha, proof, beta })),
    );
    const bad = Uint8Array.from(beta);
    bad[3] ^= 1;
    expect(() =>
      batchLeafFromPack({ ...pack, betaHex: bytesToHex(bad) }),
    ).toThrow(/does not match/);
  });
});

describe("verifyBatchCommitEndToEnd", () => {
  const { sk, pk } = generateKeyPair();
  const owner = Keypair.generate().publicKey;
  const label = encodeLabel("gacha");
  const packs = Array.from({ length: 6 }, (_, k) => {
    const alpha = sha256(new TextEncoder().encode(`alpha-${k}`));
    const { proof } = proveVRF(sk, alpha);
    return { memo: `memo-${k}`, alpha, proof, beta: vrfProofToHash(proof) };
  });
  const batch = buildBatch(packs.map((x) => batchLeafV1(x)));
  const commit: BatchCommit = {
    owner,
    label,
    root: batch.root,
    count: batch.count,
    leafVersion: 1,
    ringSeq: null,
    committedSlot: 1n,
    txSignature: "sig",
    slot: 1,
  };
  const authority: OnChainAuthority = {
    owner,
    pk,
    suite: 3,
    frozen: true,
    revoked: false,
    label,
  };
  const base = {
    authority,
    batch: commit,
    memo: packs[4].memo,
    alpha: packs[4].alpha,
    proof: packs[4].proof,
    index: 4,
    path: batch.path(4),
  };

  it("accepts a committed result", () => {
    const r = verifyBatchCommitEndToEnd(base);
    expect(r.valid).toBe(true);
    expect(r.reasons).toEqual([]);
    expect(
      r.authorityAddress.equals(
        deriveAuthorityAddress(owner, label, CC_VRF_PROGRAM_ID),
      ),
    ).toBe(true);
  });

  it("refuses each broken binding", () => {
    const cases: [string, Partial<typeof base>, string][] = [
      ["other memo", { memo: "memo-5" }, "leaf-not-in-batch"],
      ["other index", { index: 3 }, "leaf-not-in-batch"],
      ["other proof", { proof: packs[3].proof }, "leaf-not-in-batch"],
      [
        "unfrozen",
        { authority: { ...authority, frozen: false } },
        "authority-not-frozen",
      ],
      [
        "other owner",
        { batch: { ...commit, owner: Keypair.generate().publicKey } },
        "batch-authority-mismatch",
      ],
      [
        "other label",
        { batch: { ...commit, label: encodeLabel("other") } },
        "batch-authority-mismatch",
      ],
      [
        "leaf v2",
        { batch: { ...commit, leafVersion: 2 } },
        "unsupported-leaf-version-2",
      ],
      [
        "wrong pk",
        { authority: { ...authority, pk: generateKeyPair().pk } },
        "ecvrf-verify-failed",
      ],
    ];
    for (const [name, change, reason] of cases) {
      const r = verifyBatchCommitEndToEnd({ ...base, ...change });
      expect(r.valid, name).toBe(false);
      expect(r.reasons, name).toContain(reason);
    }
  });

  it("treats revoked as information only", () => {
    const r = verifyBatchCommitEndToEnd({
      ...base,
      authority: { ...authority, revoked: true },
    });
    expect(r.valid).toBe(true);
    expect(r.notes).toEqual(["authority-revoked"]);
  });
});
